typedef struct
{
    uint8_t * p_img;
    uint32_t  width;
    int       scale;
} canvas_t;

typedef struct
{
    int x;
    int y;
} pixel_pos_t;

static size_t longest_line(const hud_text_t * p_text)
{
    size_t longest = 0;
    int    i       = 0;

    for (i = 0; i < p_text->line_count; i++)
    {
        const char * p_line = p_text->pp_lines[i];
        size_t       len    = 0;

        if (NULL != p_line)
        {
            len = strnlen(p_line, MAX_LINE_CHARS);
        }
        if (len > longest)
        {
            longest = len;
        }
    }

    return longest;
}

static void fill_pixel_block(const canvas_t * p_cv, pixel_pos_t pos)
{
    int sy = 0;

    for (sy = 0; sy < p_cv->scale; sy++)
    {
        size_t offset = ((((size_t)pos.y + (size_t)sy) * p_cv->width) +
                         (size_t)pos.x) * RGBA_BYTES;

        memset(p_cv->p_img + offset, (int)WHITE,
               (size_t)p_cv->scale * RGBA_BYTES);
    }
}

static void blit_glyph_row(const canvas_t * p_cv, uint8_t bits,
                           pixel_pos_t pos)
{
    int         col   = 0;
    pixel_pos_t block = pos;

    for (col = 0; col < GLYPH_W; col++)
    {
        block.x = pos.x + (col * p_cv->scale);
        if (0U != ((bits >> col) & 1U))
        {
            fill_pixel_block(p_cv, block);
        }
    }
}

static void blit_glyph(const canvas_t * p_cv, char ch, pixel_pos_t pos)
{
    int         idx = (int)((unsigned char)ch) - FIRST_GLYPH;
    int         row = 0;
    pixel_pos_t at  = pos;

    if ((idx < 0) || (idx >= GLYPH_COUNT))
    {
        goto cleanup;
    }
    for (row = 0; row < GLYPH_H; row++)
    {
        at.y = pos.y + (row * p_cv->scale);
        blit_glyph_row(p_cv, g_font[idx][row], at);
    }

cleanup:

    return;
}

static void blit_line(const canvas_t * p_cv, const char * p_line, int py)
{
    size_t      i   = 0;
    size_t      len = 0;
    pixel_pos_t pos;

    pos.x = 0;
    pos.y = py;
    if (NULL == p_line)
    {
        goto cleanup;
    }
    len = strnlen(p_line, MAX_LINE_CHARS);
    for (i = 0; i < len; i++)
    {
        pos.x = (int)i * GLYPH_W * p_cv->scale;
        blit_glyph(p_cv, p_line[i], pos);
    }

cleanup:

    return;
}

typedef struct
{
    hud_wrapped_t * p_out;
    int             col;
} wrap_cursor_t;

static int word_length(const char * p_text)
{
    int len = 0;

    while (('\0' != p_text[len]) && (' ' != p_text[len]) &&
           ('\n' != p_text[len]))
    {
        len++;
    }

    return len;
}

static void wrap_newline(wrap_cursor_t * p_cur)
{
    p_cur->p_out->line_count++;
    p_cur->col = 0;
    if (p_cur->p_out->line_count < HUD_MAX_LINES)
    {
        p_cur->p_out->lines[p_cur->p_out->line_count][0] = '\0';
    }
}

static void wrap_append_word(wrap_cursor_t * p_cur, const char * p_word,
                             int wlen)
{
    char * p_line = NULL;
    int    take   = 0;

    if ((p_cur->col > 0) && ((p_cur->col + 1 + wlen) > HUD_WRAP_COLS))
    {
        wrap_newline(p_cur);
    }
    if (p_cur->p_out->line_count >= HUD_MAX_LINES)
    {
        goto cleanup;
    }
    p_line = p_cur->p_out->lines[p_cur->p_out->line_count];
    if (p_cur->col > 0)
    {
        p_line[p_cur->col] = ' ';
        p_cur->col++;
    }
    take = HUD_WRAP_COLS - p_cur->col;
    if (take > wlen)
    {
        take = wlen;
    }
    memcpy(p_line + p_cur->col, p_word, (size_t)take);
    p_cur->col += take;
    p_line[p_cur->col] = '\0';

cleanup:

    return;
}

void hud_wrap_text(const char * p_text, hud_wrapped_t * p_out)
{
    const char *  p_cur = p_text;
    int           i     = 0;
    wrap_cursor_t cur;

    if (NULL == p_out)
    {
        goto cleanup;
    }
    memset(p_out, 0, sizeof(*p_out));
    cur.p_out = p_out;
    cur.col   = 0;
    while ((NULL != p_cur) && ('\0' != *p_cur) &&
           (p_out->line_count < HUD_MAX_LINES))
    {
        int wlen = word_length(p_cur);

        wrap_append_word(&cur, p_cur, wlen);
        p_cur += wlen;
        if ('\n' == *p_cur)
        {
            wrap_newline(&cur);
            p_cur++;
        }
        while (' ' == *p_cur)
        {
            p_cur++;
        }
    }
    if (p_out->line_count < HUD_MAX_LINES)
    {
        p_out->line_count++;
    }
    for (i = 0; i < p_out->line_count; i++)
    {
        p_out->pp_lines[i] = p_out->lines[i];
    }

cleanup:

    return;
}

uint8_t * hud_render(const hud_text_t * p_text, uint32_t * p_width,
                     uint32_t * p_height)
{
    uint8_t * p_out       = NULL;
    size_t    cols        = 0;
    uint32_t  width       = 0;
    uint32_t  height      = 0;
    int       line_stride = 0;
    int       line        = 0;
    canvas_t  cv;

    memset(&cv, 0, sizeof(cv));
    if ((NULL == p_text) || (NULL == p_text->pp_lines) ||
        (p_text->line_count <= 0) || (p_text->scale < 1) ||
        (NULL == p_width) || (NULL == p_height))
    {
        goto cleanup;
    }
    cols = longest_line(p_text);
    if (0U == cols)
    {
        goto cleanup;
    }
    line_stride = (GLYPH_H + LINE_GAP_PX) * p_text->scale;
    width       = (uint32_t)(cols * (size_t)(GLYPH_W * p_text->scale));
    height      = (uint32_t)((size_t)p_text->line_count *
                             (size_t)line_stride);
    cv.p_img    = (uint8_t *)calloc((size_t)width * (size_t)height,
                                    RGBA_BYTES);
    if (NULL == cv.p_img)
    {
        goto cleanup;
    }
    cv.width = width;
    cv.scale = p_text->scale;
    for (line = 0; line < p_text->line_count; line++)
    {
        blit_line(&cv, p_text->pp_lines[line], line * line_stride);
    }
    *p_width  = width;
    *p_height = height;
    p_out     = cv.p_img;
    cv.p_img  = NULL;

cleanup:
    if (NULL != cv.p_img)
    {
        free(cv.p_img);
    }

    return p_out;
}
